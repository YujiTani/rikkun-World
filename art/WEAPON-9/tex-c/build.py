PAL = {"W": "#FFFDF4", "C": "#FFF0B0", "Y": "#C8961E", "Y3": "#7A5A20", "G": "#4CC57E", "Bl": "#5AB4FF", "M": "#A882F0"}
STEP = 22  # あみの 目（1 まわり 16 こ）


def tile():
    """88×112 × 2 コマ。ななめ 2 方向の 1 点の 線（クリーム、ところどころ 金）。目の 交わりに 3×3 の ほうせき（みどり・青・むらさき）。
    2 コマ目は ほうせきの 色が 1 つ ずれる（明るさは かえない）"""
    s = Sprite(TW * 2, TH)
    jew = [PAL["G"], PAL["Bl"], PAL["M"]]
    for f in range(2):
        for y in range(8, TH):
            for x in range(TW):
                a, b = (x + y) % STEP, (x - y) % STEP
                if a == 0 or b == 0:
                    s.px(f * TW + x, y, PAL["Y"] if (x // 2 + y // 2) % 4 == 0 else PAL["C"])
        k = 0
        for y in range(STEP // 2, TH - 1, STEP // 2):
            for x in range(0, TW, STEP // 2):
                if (x + y) % STEP == 0 and (x - y) % STEP == 0:
                    tex9.plus_star(s, f * TW + x % TW, y, 1, PAL["W"], jew[(k + f) % 3])
                    k += 1
    return s


RIM = [(None, 0)] * 11 + [(PAL["C"], 255), (PAL["W"], 255), (PAL["W"], 255), (PAL["Y"], 255), (D, 255)]


def slash_color(f, q, u, x, y):
    # 外（前の へり）= クリーム白 → みどり → 青 → むらさき（かたい しま、網 なし）
    return PAL["W"] if f < 0.24 else PAL["G"] if f < 0.5 else PAL["Bl"] if f < 0.76 else PAL["M"]


def slash_frame(view, i, tail, head, sc, thin):
    return tex9.slash_px(view, tail, head, sc, thin, {"kind": "chevron", "T": 10}, slash_color, cap="point")


TRI = [(0, 0), (1, 0), (2, 0), (0, 1), (1, 1), (0, 2)]


def slash_deco(s, view, i):
    """「く」の 外へ 三角の かけら（3 点の 直角三角）。のこりで 3 こ、きえかけで 1 こ"""
    ky = 1.0 if view == "side" else 0.6
    cy = 38 if view == "side" else 40.5
    spots = [(0.25, 34, PAL["G"]), (0.55, 35, PAL["Bl"]), (0.85, 31, PAL["G"])]
    n = [0, 2, 3, 1][i]
    for qq, rr, c in spots[:n]:
        th = math.radians(165 - qq * 150)
        x = round(32 + rr * math.cos(th))
        y = round(cy - rr * math.sin(th) * ky)
        for dx, dy in TRI:
            s.px(x + dx, y + dy, PAL["W"] if (dx, dy) == (0, 0) else c)


