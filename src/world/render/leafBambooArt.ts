import { bambooMode, leafMode } from './leafBambooMode';

export type Rgba = readonly [number, number, number, number];

const T = 16;

function hex(c: string, a = 255): Rgba {
  const n = parseInt(c.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255, a];
}

function paint(rows: readonly string[], ink: Record<string, Rgba>): Rgba[] {
  const empty: Rgba = [0, 0, 0, 0];
  const out: Rgba[] = [];
  for (let y = 0; y < T; y++) {
    const row = rows[y] ?? '';
    if (row.length !== T) throw new Error(`leaf tile row ${y} is ${row.length}`);
    for (let x = 0; x < T; x++) out.push(ink[row[x] ?? '.'] ?? empty);
  }
  return out;
}

