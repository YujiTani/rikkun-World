/** たけ。0〜3 列・上 8 行が 葉（すきあり）。4 列目から 稈。節は 0, 5, 10, 15 行 */
function bambooRows(): string[] {
  const leaf = ['55.55.', '555554', '.5554.', '..554.', '...54.', '....4.', '.5.5..', '5544..'];
  const rows: string[] = [];
  for (let y = 0; y < T; y++) {
    let row = '';
    const node = y % 5 === 0;
    for (let x = 0; x < T; x++) {
      if (y < 8 && x < 6) {
        row += leaf[y]![x];
        continue;
      }
      if (x < 6) {
        row += '3';
        continue;
      }
      const edge = x === 6 || x === 15;
      const bright = x === 9 || x === 10;
      row += node ? '1' : edge ? '2' : bright ? '4' : '3';
    }
    rows.push(row);
  }
  return rows;
}

