function hex(c: string): Rgba {
  const n = parseInt(c.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255, 255];
}

/** 色: 2 かげ・3 地・4 光・5 光の 先（1 は 使っていない 予備の こい かげ） */
const tones = (a: string, b: string, c: string, d: string, e: string): Record<string, Rgba> => ({ '1': hex(a), '2': hex(b), '3': hex(c), '4': hex(d), '5': hex(e) });

const ART = {
  leaves: [LEAF, tones('#368A33', '#3D9636', '#46A23A', '#55B043', '#6DC04F')],
  momiji_leaves: [MOMIJI, tones('#C2552A', '#CC6230', '#D97436', '#E68A3C', '#F0A548')],
  matsu_leaves: [MATSU, tones('#27603A', '#2C6A3E', '#327443', '#3F874B', '#55A058')],
} as const;

export type LeafTileName = keyof typeof ART;

export function paintLeafTile(name: LeafTileName): Rgba[] {
  const [rows, ink] = ART[name];
  const out: Rgba[] = [];
  for (let y = 0; y < T; y++) {
    const row = rows[y]!;
    if (row.length !== T) throw new Error(`leaf tile ${name} row ${y}`);
    for (let x = 0; x < T; x++) out.push(ink[row[x]!]!);
  }
  return out;
}
