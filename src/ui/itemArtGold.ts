const CLEAR: Rgba = [0, 0, 0, 0];

/** きんの そうび・きん・はらぱんみみず の 16x16 */
export function goldItemPixels(item: GoldItemId): Rgba[] {
  const out: Rgba[] = [];
  for (const row of ROWS[item]) {
    for (const ch of row) {
      const c = PAL[ch];
      out.push(c === undefined ? CLEAR : [(c >> 16) & 255, (c >> 8) & 255, c & 255, 255]);
    }
  }
  return out;
}
